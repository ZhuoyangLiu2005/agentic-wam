#!/usr/bin/env python3
"""Assemble a training data config from one or more codegen/sim dataset manifests (dataset.yaml).

    python robotwin/dataprep/data_config.py --datasets <d1>/dataset.yaml <d2>/dataset.yaml --out configs/robotwin/data/<name>.yaml
        [--split train|all] [--norm-stats PATH] [--text-cache-root DIR]

Each manifest (written by codegen/sim scripts/make_dataset.py) names the LeRobot dir and the stage-slicing cache; this
script emits one RobotVideoDataset block per manifest on top of data_base.yaml next to this file (the
shared shape_meta / processor / common anchors). `--split train` uses episodes_train.json (first 50 kept episodes),
`all` uses every kept episode. `--text-cache-root` sets cosmos_text_cache_dir=<root>/<task> per dataset (the
Cosmos-Reason1 prompt-embedding cache, built by text_cache.py; the backbone requires it).
"""
import argparse
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent


def block(m, split, text_root):
    if not m.get("slices"):
        sys.exit(f"{m['task']}: no slicing cache (program without stage markers?) — the code stream needs it")
    s = m["slices"]
    lines = [f"      # ---- {m['task']} ({m['episodes']['kept']} episodes, program sha {m['program_sha256'][:12]}) ----",
             "      - <<: *common",
             f"        dataset_dirs: [{m['lerobot_dir']}]",
             f"        episode_indices:      {s['episodes_' + split]}",
             f"        code_slices_cache_dir: {s['slices_ep']}",
             f"        cycle_cache_path:     {s['cycle_by_idx']}"]
    if text_root:
        lines.append(f"        cosmos_text_cache_dir: {Path(text_root) / m['task']}")
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--datasets", nargs="+", required=True, help="dataset.yaml manifests from codegen/sim")
    ap.add_argument("--out", required=True)
    ap.add_argument("--split", choices=["train", "all"], default="train")
    ap.add_argument("--norm-stats", required=True, help="14-D joint normalisation stats json (RoboTwin 2.0 dataset_stats.json)")
    ap.add_argument("--text-cache-root", default=None)
    a = ap.parse_args()
    ms = [yaml.safe_load(open(p)) for p in a.datasets]
    base = (HERE / "data_base.yaml").read_text().replace("__NORM_STATS__", a.norm_stats)
    body = "\n".join(block(m, a.split, a.text_cache_root) for m in ms)
    text = (f"# Generated by robotwin/dataprep/data_config.py from: {', '.join(a.datasets)}\n" + base +
            "train:\n  _target_: agenticwam.datasets.lerobot.deadline_dataset.DeadlineDataset\n  seconds: 60.0\n  max_retries: 2\n"
            "  dataset:\n    _target_: torch.utils.data.ConcatDataset\n    datasets:\n" + body + "\n\nval: null\n")
    Path(a.out).write_text(text)
    yaml.safe_load(text)
    print(f"wrote {a.out}: {len(ms)} datasets, {sum(m['episodes']['kept'] for m in ms)} kept episodes, split={a.split}")


if __name__ == "__main__":
    main()
