#!/usr/bin/env python
"""Mine the HUMAN SUBTASK-ANNOTATION vocabulary against the generated code —
the coordinator's skill-candidate source that names skills after what the
annotators already called the maneuvers.

For every slice across the selected run dirs, the slice's annotation label is
normalized to its head verb (e.g. "Zip the zipper on the pencil case." -> zip)
and grouped with the ordered robot-API call sequence the actor generated for
it. The report shows, per verb: how often it occurs, across how many tasks,
which call sequences realize it (with frequencies), and how many instances had
ZERO observed contact events (detector-gap pressure). A verb that is frequent,
cross-task, and realized by a CONSISTENT call sequence is a callable-skill
candidate whose NAME the annotation vocabulary already chose; an inconsistent
one is an audit lead.

    $PY scripts/mine_label_patterns.py --embodiment ego --tags e1,e2
    -> docs/progress/label_patterns_<embodiment>.md
"""
from __future__ import annotations

import argparse
import json
import os
import re
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

_CALL = re.compile(r"\brobot\.(\w+)\(")
_SKILL_CALL = re.compile(r"^\s*(\w+)\(robot\b")


def head_verb(label: str) -> str:
    words = re.findall(r"[a-z]+", (label or "").lower())
    return words[0] if words else "(none)"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    from codegen import config
    ap.add_argument("--embodiment", default=config.embodiment(),
                    choices=["yam", "ego", "tianji_sharpa", "yam_sft"])
    ap.add_argument("--tags", default="", help="comma-separated round tags (default: all runs)")
    args = ap.parse_args()
    os.environ["CODEGEN_EMBODIMENT"] = args.embodiment
    from codegen.embodiments import get_spec
    spec = get_spec(args.embodiment)
    tags = [t for t in args.tags.split(",") if t]

    groups = defaultdict(lambda: {"n": 0, "tasks": set(), "seqs": Counter(),
                                  "zero_ev": 0, "labels": Counter()})
    n_runs = n_bad = 0
    # Run dirs are <task>/<model>/<episode>/<tag>/ — glob from the TASK root, not
    # from one episode's directory. Globbing `run_dir(task, "X").parent` only ever
    # saw <model>/episode_000/<tag>, i.e. one episode of one model: on a corpus
    # with 250 episodes per task that is 0.4% of the slices, and exactly 0% for a
    # campaign whose units are episodes >= 1. The miner is what NAMES candidate
    # skills, so a blind spot here silently shapes the library.
    for task in spec.list_tasks():
        task_root = spec.run_dir(task, "X").parents[2]        # .../<task>/
        for tag in tags or [None]:
            pattern = f"*/*/{tag}/trace.json" if tag else "*/*/*/trace.json"
            rds = [p.parent for p in task_root.glob(pattern)]
            for rd in rds:
                tr = rd / "trace.json"
                if not tr.exists():
                    continue
                try:
                    slices = json.loads(tr.read_text()).get("slices", [])
                except (json.JSONDecodeError, OSError) as e:
                    # A run dir killed mid-write (actor timeout, disk full) leaves a
                    # truncated trace.json. Skipping ONE is right; dying takes the
                    # whole corpus scan down with it, on a corpus where a few bad
                    # dirs are certain.
                    n_bad += 1
                    print(f"[mine] SKIP unreadable {rd}: {e}", file=sys.stderr)
                    continue
                n_runs += 1
                for s in slices:
                    lab = s.get("label") or ""
                    code = s["code"]["lines"] if isinstance(s.get("code"), dict) else (s.get("code") or [])
                    text = "\n".join(code)
                    seq = tuple(_CALL.findall(text) +
                                [f"{m}()" for m in _SKILL_CALL.findall(text)])
                    g = groups[head_verb(lab)]
                    g["n"] += 1
                    g["tasks"].add(task)
                    g["seqs"][seq or ("(no calls)",)] += 1
                    g["labels"][lab[:70]] += 1
                    if not s["grip_reconcile"]["observed_grippers"]:
                        g["zero_ev"] += 1

    out = [f"# Annotation-label patterns — {args.embodiment}"
           + (f" (tags: {', '.join(tags)})" if tags else " (all runs)"),
           "",
           f"> GENERATED by scripts/mine_label_patterns.py over {n_runs} run dirs"
           + (f" ({n_bad} unreadable, skipped)." if n_bad else "."),
           "> A frequent, cross-task verb realized by a CONSISTENT call sequence is a",
           "> callable-skill candidate NAMED by the annotation vocabulary; zero-event",
           "> counts show detector-gap pressure on that verb.", ""]
    for verb, g in sorted(groups.items(), key=lambda kv: -kv[1]["n"]):
        out.append(f"## {verb} — {g['n']} slices, {len(g['tasks'])} tasks, "
                   f"{g['zero_ev']} zero-event")
        for lab, c in g["labels"].most_common(3):
            out.append(f"- label e.g. ({c}x): {lab}")
        for seq, c in g["seqs"].most_common(5):
            out.append(f"- `{' -> '.join(seq)}` x{c}")
        out.append("")
    dst = ROOT / "docs" / "progress" / f"label_patterns_{args.embodiment}.md"
    dst.parent.mkdir(parents=True, exist_ok=True)
    dst.write_text("\n".join(out))
    print("\n".join(out[:40]))
    print(f"...\n[mine_label_patterns] wrote {dst.relative_to(ROOT)}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
