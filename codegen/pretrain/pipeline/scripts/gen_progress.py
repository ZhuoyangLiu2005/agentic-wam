#!/usr/bin/env python
"""Regenerate the data-gen progress file — the SINGLE SOURCE OF TRUTH for
round status (ASPIRE `gen_progress.py` convention: the file on disk is stale
by definition; ALWAYS regenerate before reading).

The file is an AGGREGATE view, deliberately bounded (it is read into a
coordinator's context): per-round metric rows, the library state with loader
warnings, and the frontier as a COUNT plus a short preview — never an
enumeration (a corpus-scale task x round matrix would be gigabytes). The
frontier's machine-readable form is emitted separately:

    CODEGEN_EMBODIMENT=<emb> $PY scripts/gen_progress.py
        [--emit-frontier]      also write outputs/<emb>/frontier/shard_NN.txt
                               (TASKS_PER_ROUND work units per shard, in the
                               '<task>[:<episode>]' format run_batch
                               --tasks-file consumes)

Work units are (task, episode_index) pairs (codegen.data.index); a unit is
processed when ANY round's manifest carries its (task, episode) row.
"""
from __future__ import annotations

import re

import argparse
import collections
import io
import json
import os
import shutil
import sys
from contextlib import redirect_stderr
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from codegen import config  # noqa: E402

EMB = config.embodiment()
os.environ["CODEGEN_EMBODIMENT"] = EMB   # downstream imports key off the env var
OUT = ROOT / "outputs" / EMB / "progress.md"
PREVIEW = 10


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--emit-frontier", action="store_true",
                    help="write outputs/<emb>/frontier/shard_NN.txt work-unit files")
    ap.add_argument("--tag", default=config.get("TAG"),
                    help="scope 'processed' to THIS version tag's batches "
                         "(batch_<tag>_*). Annotation is single-pass PER TAG: "
                         "a new tag sees the full corpus as frontier, a reused "
                         "tag resumes. Default: the `tag` config key; pass "
                         "--tag '' for the all-tags overview")
    args = ap.parse_args()

    from codegen.data.index import corpus_units, unit_name

    units = corpus_units(EMB)

    outputs = ROOT / "outputs"
    rounds = []
    for bdir in sorted(outputs.glob(f"{EMB}/batch_*")):
        tag = bdir.name[len("batch_"):]
        # Round dirs are batch_<tag>_r<N>; match the round suffix EXACTLY. A bare
        # startswith(tag + "_") swallows sibling tags that extend this one ("v1"
        # scoping every "v1_vanilla_r*" batch). Ported from codegen-real 7914436.
        in_scope = (not args.tag) or tag == args.tag or bool(
            re.fullmatch(re.escape(args.tag) + r"_r\d+", tag))
        summary, manifest = {}, {}
        sp, mp = bdir / "summary.json", bdir / "manifest.jsonl"
        if sp.exists():
            summary = json.loads(sp.read_text())
        if mp.exists():
            for line in mp.read_text().splitlines():
                if line.strip():
                    row = json.loads(line)
                    manifest[(row["task"], row.get("episode", "episode_000"))] = row
        rounds.append({"tag": tag, "summary": summary, "manifest": manifest,
                       "in_scope": in_scope,
                       "snapshot": (bdir / "library_snapshot").is_dir()})

    warn_buf = io.StringIO()
    with redirect_stderr(warn_buf):
        from codegen.library import SKILLS
    warnings = [ln for ln in warn_buf.getvalue().splitlines() if ln.strip()]

    # A unit is PROCESSED only if some round produced a program for it. A row
    # carrying `error` (actor crash/timeout, preflight skip, gate failure) means
    # ATTEMPTED AND EMPTY-HANDED — counting it as processed retires the unit
    # permanently, which is how a corpus-scale campaign silently loses whatever
    # fraction of the frontier the router happened to fail on. Those go back on
    # the frontier and are reported separately so the failure stays visible.
    done, failed = {}, {}
    for r in rounds:
        if not r["in_scope"]:
            continue
        for k, row in r["manifest"].items():
            (failed if row.get("error") else done)[k] = row
    failed = {k: v for k, v in failed.items() if k not in done}   # a later success wins
    frontier = [(t, i) for (t, i) in units
                if (t, f"episode_{i:03d}") not in done]

    lines = [
        "# Data-gen progress — " + EMB,
        "",
        "> GENERATED by `scripts/gen_progress.py` — the file on disk is stale by",
        "> definition; always regenerate before reading.",
        "",
        "## Rounds",
        "",
        "| tag | units | reconciled | reconcile_rate | pin_rate | skipped_events | library snapshot |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in rounds:
        s = r["summary"]
        n_rec = s.get("fully_reconciled",
                      sum(1 for row in r["manifest"].values() if row.get("reconciled")))
        lines.append(f"| {r['tag']} | {s.get('tasks', len(r['manifest']))} | {n_rec} "
                     f"| {s.get('reconcile_rate', '—')} | {s.get('pin_rate', '—')} "
                     f"| {s.get('skipped_events', '—')} "
                     f"| {'yes' if r['snapshot'] else '—'} |")
    if not rounds:
        lines.append("| (no rounds yet) | | | | | | |")

    lines += ["", f"## Skill library (embodiment: {EMB})", "",
              f"- callable skills: {', '.join(s['name'] for s in SKILLS) or '(none)'}"]
    for w in warnings:
        lines.append(f"- **LOADER WARNING** (fix or attic BEFORE dispatching): `{w}`")

    scope = f"tag '{args.tag}'" if args.tag else "any round"
    lines += ["", f"## Frontier (work units with no PROGRAM under {scope})", "",
              f"- corpus: {len(units)} units ({len({t for t, _ in units})} tasks) · "
              f"processed: {len(units) - len(frontier)} · **remaining: {len(frontier)}**"]
    if failed:
        kinds = collections.Counter(str(v.get("error")).split("(")[0].strip()
                                    for v in failed.values())
        lines.append(f"- **re-queued: {len(failed)} unit(s) were ATTEMPTED and produced "
                     f"no program** — they are back on the frontier below. Causes: "
                     + "; ".join(f"{k} x{n}" for k, n in kinds.most_common(5)))
    if frontier:
        head = ", ".join(unit_name(t, i) for (t, i) in frontier[:PREVIEW])
        more = f" … (+{len(frontier) - PREVIEW} more)" if len(frontier) > PREVIEW else ""
        lines.append(f"- next: {head}{more}")
        lines.append("- machine-readable shards: rerun with `--emit-frontier` "
                     "and dispatch each file via `run_batch --tasks-file`")
    else:
        lines.append("- (none — corpus exhausted)")
    lines.append("")

    if args.emit_frontier:
        fdir = outputs / EMB / "frontier"
        if fdir.exists():
            shutil.rmtree(fdir)          # regenerable; stale shards must not linger
        fdir.mkdir(parents=True)
        per = config.get_int("TASKS_PER_ROUND")
        shards = []
        for n, i in enumerate(range(0, len(frontier), per), 1):
            p = fdir / f"shard_{n:02d}.txt"
            p.write_text("\n".join(unit_name(t, e) for (t, e) in frontier[i:i + per]) + "\n")
            shards.append(p)
        print(f"[gen_progress] frontier -> {len(shards)} shard file(s) of <= {per} "
              f"units under {fdir.relative_to(ROOT)}", file=sys.stderr)

    OUT.parent.mkdir(parents=True, exist_ok=True)   # fresh clone: docs/progress/ may not exist
    OUT.write_text("\n".join(lines))
    print("\n".join(lines))
    print(f"[gen_progress] wrote {OUT.relative_to(ROOT)}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
