"""Stage B (+ optional tier C) — assemble an episode from the skeleton cache.

Stage B costs NO model call and opens NO video. It reads two parquet columns,
segments the episode, pastes each block's cached skeleton, and re-grounds it
against THIS episode's own gripper events. Two deterministic repairs then run:
`repair_tail` inserts head/tail events the skeleton did not emit, and
`lint_over_emission` comments out explicit gripper calls the skeleton emitted but
this episode did not have. Measured on one real task (213 episodes, 6,426
blocks): 4.1% of blocks match outright, 17.8% after repair_tail, 32.9% after both.

Blocks the skeleton cannot explain (structurally different event sequence, or no
skeleton at all) are marked ``needs_refine`` and left with block-level alignment,
exactly as an unmatched slice is in the per-episode pipeline. Tier C then
regenerates only those, and only up to a budget.

The run dir written here is the SAME schema as the per-episode pipeline, so the
gate, the viz server, the miner and any cache builder consume it unchanged.
"""
from __future__ import annotations

import json
import time
from pathlib import Path

import numpy as np

from codegen import config
from codegen.api.active import EMBODIMENT
from codegen.grounding.aperture import CONTACT_LABEL
from codegen.grounding.facts import block_events
from codegen.grounding.segment import sub_task_blocks, unmapped_ids
from codegen.library import SKILLS, skills_header
from codegen.pipeline import artifacts
from codegen.program.effects import lint_over_emission, match_grippers, repair_tail
from codegen.skeleton.store import SkeletonStore, skeleton_key


def load_state_only(spec, task: str, episode_index: int):
    """Everything the assembler needs, WITHOUT decoding a single video frame.

    Deliberately not ``spec.load_episode``: that builds a LazyClip, which opens
    the mp4 to probe its length. Stage B's whole claim is that it never touches
    video, so it goes through the spec's STATE-ONLY reader instead — which is
    per-embodiment because the source layout is (codegen.data.readers for yam / ego)."""
    return spec.load_state(task, episode_index)


def _slices_of(ep, spec):
    """The ordered slices, with the SAME two skip rules as the per-episode path."""
    blocks = sub_task_blocks(ep["sub_id"], ep["text"], noise_labels=spec.noise_labels)
    merged = []
    for (bs, be, label, noise) in blocks:
        if label:
            merged.append([bs, be, label, None, True])
        elif (merged and merged[-1][2] is None
                and merged[-1][4] == (noise is not None)):
            merged[-1][1] = be
            merged[-1][3] = merged[-1][3] or noise
        else:
            merged.append([bs, be, None, noise, noise is not None])
    return [{"bs": bs, "be": be, "label": label,
             "noise": noise if all_noise else None}
            for (bs, be, label, noise, all_noise) in merged]


def assemble(task: str, episode_index: int, store: SkeletonStore, prompt_version: str,
             tag: str, coder_model: str, refine_budget: int = 0, log=print) -> dict:
    """Build one episode's run dir from the cache. Returns a summary row."""
    from codegen.embodiments import get_spec
    t0 = time.time()
    spec = get_spec(EMBODIMENT)
    ep = load_state_only(spec, task, episode_index)
    T = ep["T"]
    bad = unmapped_ids(ep["sub_id"], ep["text"])
    if bad:
        raise RuntimeError(f"{len(bad)} sub-task id(s) missing from the id->text map "
                           f"({bad[:6]}) — the annotation mapping is broken, not the data")

    from codegen.actor.client import model_short
    out = spec.run_dir(task, tag, model_short(coder_model),
                       episode_id=f"episode_{episode_index:03d}")
    out.mkdir(parents=True, exist_ok=True)

    lines = [f'# {spec.display_name} (skeleton-assembled, unit=subtask) :: "{ep["instruction"]}"',
             f"# model: skeletons generated by {coder_model}; THIS episode was assembled",
             "#   from the cache with no model call. Per-slice `source` in trace.json",
             "#   says which lines are cache-reused and which were regenerated.",
             "import numpy as np"]
    lines += skills_header(SKILLS)
    frame_src_block = [None] * T
    grip_pins = []
    trace, rec = [], []
    n_refined = n_missing = n_repaired = n_linted = n_matched = 0
    # matched BEFORE any repair. This is the only ungameable one: a skeleton that
    # emits no gripper call at all lets repair_tail transcribe every observed
    # event straight from the detector, and then `matched`/`pin_rate` both read
    # 1.0 with zero model-written contact code. `matched_raw` reads ~0 there.
    n_matched_raw = 0

    for i, sl in enumerate(_slices_of(ep, spec)):
        bs, be, label = sl["bs"], sl["be"], sl["label"]
        grips = block_events(ep["per_arm"], bs, be)
        observed = [f"{k}_{a}" for (_f, a, k) in grips]

        if sl["noise"] or not label:
            # annotated noise is always skipped; an unlabeled span has no skeleton
            # to reuse, so it is left for tier C rather than silently coded
            why = "noise" if sl["noise"] else "unlabeled"
            trace.append({"slice": i, "label": label, "kind": "subtask",
                          "start": bs, "end": be, "skipped": True,
                          "noise_label": sl["noise"], "skip_reason": why,
                          "skipped_events": len(grips), "frames": [],
                          "source": "skipped",
                          "needs_refine": why == "unlabeled" and bool(grips),
                          "grip_reconcile": {"coder_grippers": [], "observed_grippers": observed,
                                             "observed_frames": [int(f) for (f, _a, _k) in grips],
                                             "matched": not grips},
                          "code": {"lines": []},
                          "validation": {"ok": True, "problems": [], "repairs": 0}})
            continue

        key = skeleton_key(label, prompt_version, EMBODIMENT)
        skel = store.get(key)
        if skel is None:
            n_missing += 1
            code, source, val = ([f"# (no skeleton for {label!r} at prompt_version "
                                  f"{prompt_version}; run stage A)"], "missing",
                                 {"ok": False, "problems": ["no skeleton"], "repairs": 0})
            anchors, report = [], {"coder_grippers": [], "observed_grippers": observed,
                                   "observed_frames": [int(f) for (f, _a, _k) in grips],
                                   "matched": False}
            needs_refine = True
        else:
            code = list(skel["code"])
            val = {"ok": bool(skel.get("valid", True)),
                   "problems": skel.get("problems", []), "repairs": 0}
            anchors, report = match_grippers(code, grips)
            matched_raw = report["matched"]
            tail = lint = 0
            if not matched_raw and config.get_bool("REPAIR_TAIL"):
                # two deterministic directions, measured to be about equally
                # common on reused skeletons: too FEW events (insert from the
                # sensor) and too MANY (comment the redundant explicit call out)
                code, tail = repair_tail(code, grips)
                if tail:
                    anchors, report = match_grippers(code, grips)
                if not report["matched"]:
                    code, lint = lint_over_emission(code, grips)
                    if lint:
                        anchors, report = match_grippers(code, grips)
            report["matched_raw"] = matched_raw
            report["tail_repaired"] = tail
            report["over_emission_linted"] = lint
            n_repaired += bool(tail)
            n_linted += bool(lint)
            n_matched += bool(report["matched"])
            n_matched_raw += bool(matched_raw)
            source = ("skeleton" if matched_raw else
                      "skeleton+repair" if tail else
                      "skeleton+lint" if lint else "skeleton")
            needs_refine = not report["matched"]

        # tier C: regenerate this block from THIS episode's frames, budget-capped
        if needs_refine and refine_budget > 0 and skel is not None:
            try:
                from codegen.actor.client import load_key
                from codegen.skeleton.generate import generate_one
                r = generate_one(label, {"task": task, "episode": episode_index,
                                         "bs": bs, "be": be},
                                 spec, load_key(), coder_model, log=log)
                code = r["code"]
                anchors, report = match_grippers(code, grips)
                report["matched_raw"] = report["matched"]
                report["tail_repaired"] = 0
                val = {"ok": r["valid"], "problems": r["problems"], "repairs": r["repairs"]}
                source = "regenerated"
                refine_budget -= 1
                n_refined += 1
                needs_refine = not report["matched"]
            except Exception as e:
                log(f"[tier-c] {task}:{episode_index} slice {i}: {type(e).__name__}: {e}")

        lines.append("")
        lines.append(f"# --- {label}  (frames {bs}-{be})")
        lns = []
        for cl in code:
            lines.append(cl)
            lns.append(len(lines))
        if not lns:
            lines.append(f"# (empty skeleton for slice {i})")
            lns = [len(lines)]
        for (off, gf) in anchors:
            if 0 <= off < len(lns) and 0 <= gf < T:
                grip_pins.append([int(gf), int(lns[off])])
        for t in range(bs, min(be, T)):
            frame_src_block[t] = [lns[0], lns[-1]]
        rec.append({"label": label, "kind": "subtask", "start": bs, "end": be,
                    "frames": [], "vlm": f"(skeleton {key[:8]})", "code": code,
                    "grip_reconcile": report})
        trace.append({"slice": i, "label": label, "kind": "subtask",
                      "start": bs, "end": be, "frames": [],
                      "source": source, "skeleton_key": key,
                      "skeleton_from": (skel or {}).get("provenance"),
                      "needs_refine": needs_refine,
                      "frame_anchors": "skeleton",
                      "label_contact_zero_events": bool(
                          label and CONTACT_LABEL.search(label) and not grips),
                      "grip_reconcile": report,
                      "code": {"lines": code},
                      "validation": val})

    last = None                      # frames outside any coded block inherit the
    for t in range(T):               # previous block
        if frame_src_block[t] is None:
            frame_src_block[t] = last or [1, 1]
        else:
            last = frame_src_block[t]

    (out / artifacts.PROGRAM).write_text("\n".join(lines) + "\n")
    (out / artifacts.LINES).write_text(json.dumps(
        {"program": artifacts.PROGRAM, "frame_src_block": frame_src_block,
         "grip_pins": sorted(grip_pins)}))
    (out / artifacts.CHUNKS).write_text(json.dumps(
        {"instruction": ep["instruction"], "T": int(T), "unit": "subtask", "phases": rec}, indent=2))
    coded = [s for s in trace if not s.get("skipped")]
    (out / artifacts.TRACE).write_text(json.dumps(
        {"task": task, "instruction": ep["instruction"], "unit": "subtask",
         "coder_model": coder_model, "assembler": "skeleton",
         "prompt_version": prompt_version,
         "vanilla": False, "prompt_events": EMBODIMENT == "yam",
         "frame_gap": None, "max_slice_frames": config.get_int("MAX_SLICE_FRAMES"),
         "video_stream": None, "capped_slices": 0,
         "unsegmented": not coded,
         "boosted_events": {sd: [list(e) for e in (ep["per_arm"][sd].get("boosted") or [])]
                            for sd in ("left", "right")},
         "skills": [s["name"] for s in SKILLS],
         "skeleton_stats": {"slices": len(coded), "matched": n_matched,
                            "matched_raw": n_matched_raw,
                            "tail_repaired": n_repaired, "over_emission_linted": n_linted,
                            "regenerated": n_refined, "missing_skeleton": n_missing},
         "cost": {"model_calls": n_refined, "seconds_in_model": 0.0,
                  "wall_seconds": round(time.time() - t0, 2),
                  "prompt_tokens": 0, "completion_tokens": 0,
                  "throttled": 0, "throttle_seconds": 0.0, "throttle_sample": []},
         "n_slices": len(trace), "slices": trace}, indent=2))
    return {"task": task, "episode": f"episode_{episode_index:03d}",
            "run_dir": str(out), "slices": len(coded), "matched": n_matched,
            "matched_raw": n_matched_raw,
            "tail_repaired": n_repaired, "over_emission_linted": n_linted,
            "regenerated": n_refined, "missing_skeleton": n_missing, "grip_pins": len(grip_pins),
            "observed_events": sum(len(s["grip_reconcile"]["observed_grippers"])
                                   for s in coded),
            "wall_seconds": round(time.time() - t0, 2)}
